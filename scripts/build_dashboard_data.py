#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""build_dashboard_data.py — 读取分析 CSV，生成仪表盘嵌入 JS 数据文件"""

import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(os.path.dirname(HERE), "data")


# ── helpers ──────────────────────────────────────────────────────────────────

def _safe_float(val, ndigits=None):
    """将字符串安全转 float，空字符串返回 None，ndigits 控制 round。"""
    if val is None or val.strip() == "":
        return None
    v = float(val)
    return round(v, ndigits) if ndigits is not None else v


def _safe_int(val):
    if val is None or val.strip() == "":
        return None
    return int(val)


def read_csv(filename):
    """读取 CSV 文件，返回 list[dict]。"""
    path = os.path.join(DATA, filename)
    rows = []
    with open(path, encoding="utf-8-sig") as f:
        for r in csv.DictReader(f):
            rows.append(r)
    return rows


# ── build each block ─────────────────────────────────────────────────────────

def build_micro_data():
    """微观多尺度明细 → MICRO_DATA"""
    raw = read_csv("微观多尺度明细.csv")
    out = []
    for r in raw:
        out.append({
            "L":       int(r["窗口长度"]),
            "d0":      r["起日"],
            "d1":      r["止日"],
            "F":       _safe_float(r["F_pct"], 2),
            "R":       _safe_float(r["R_pct"], 2),
            "G":       _safe_float(r["G_pp"], 2),
            "A":       _safe_float(r["A"], 4),
            "bucket":  r.get("幅度档", "") or "",
            "stale0":  _safe_int(r.get("lag0", "")),
            "stale1":  _safe_int(r.get("lag1", "")),
        })
    return out


def build_scale_curve():
    """尺度曲线 → SCALE_CURVE"""
    raw = read_csv("尺度曲线.csv")
    out = []
    for r in raw:
        out.append({
            "L":        int(r["窗口长度"]),
            "threshold": f">={float(r['F阈值_pct']):.0f}%",
            "n_up":     int(r["上涨窗口数"]),
            "n_dn":     int(r["下跌窗口数"]),
            "g_up":     _safe_float(r["G涨中位_pp"], 2),
            "g_dn":     _safe_float(r["G跌中位_pp"], 2),
            "asym":     _safe_float(r["非对称差_pp"], 2),
            "slope":    _safe_float(r["OLS斜率"], 4),
            "r_up":     _safe_float(r["R涨中位_pct"], 2),
            "r_dn":     _safe_float(r["R跌中位_pct"], 2),
            "rf_up":    _safe_float(r["R涨_RF中位"], 3),
            "rf_dn":    _safe_float(r["R跌_RF中位"], 3),
        })
    return out


def build_micro_summary():
    """微观多尺度汇总 → MICRO_SUMMARY（仅保留汇总行，按窗口长度分组）"""
    raw = read_csv("微观多尺度汇总.csv")
    out = {}
    for r in raw:
        if r["行类型"] != "汇总":
            continue
        L = int(r["窗口长度"])
        key = str(L)
        out[key] = {
            "n":          int(r["总窗口数"]),
            "valid":      int(r["有效窗口数"]),
            "n_up":       int(r["上涨窗口数"]),
            "n_dn":       int(r["下跌窗口数"]),
            "f_up_med":   _safe_float(r["上涨_F中位_pct"], 2),
            "r_up_med":   _safe_float(r["上涨_R中位_pct"], 2),
            "g_up_med":   _safe_float(r["上涨_G中位_pp"], 2),
            "rf_up_med":  _safe_float(r["上涨_RF中位"], 3),
            "f_dn_med":   _safe_float(r["下跌_F中位_pct"], 2),
            "r_dn_med":   _safe_float(r["下跌_R中位_pct"], 2),
            "g_dn_med":   _safe_float(r["下跌_G中位_pp"], 2),
            "rf_dn_med":  _safe_float(r["下跌_RF中位"], 3),
            "asym":       _safe_float(r["非对称差_G涨减G跌_pp"], 2),
            "slope":      _safe_float(r["OLS斜率_R~F"], 4),
            "threshold":  f">={float(r['F阈值_pct']):.0f}%",
        }
    return out


def build_synthesis_data():
    """尝试读取尺度响应曲线 + 微观宏观桥接（scale_synthesis.py 产出，可能不存在）"""
    result = {"response_curves": [], "bridges": []}

    # 尺度响应曲线
    try:
        raw = read_csv("尺度响应曲线.csv")
        for r in raw:
            result["response_curves"].append(r)
    except FileNotFoundError:
        pass

    # 微观宏观桥接
    try:
        raw = read_csv("微观宏观桥接.csv")
        for r in raw:
            result["bridges"].append(r)
    except FileNotFoundError:
        pass

    return result


# ── main ─────────────────────────────────────────────────────────────────────

def main():
    micro_data = build_micro_data()
    scale_curve = build_scale_curve()
    micro_summary = build_micro_summary()
    synthesis = build_synthesis_data()

    out_path = os.path.join(DATA, "dashboard_data.js")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by build_dashboard_data.py — DO NOT EDIT\n")
        f.write(f"const MICRO_DATA = {json.dumps(micro_data, ensure_ascii=False)};\n\n")
        f.write(f"const SCALE_CURVE = {json.dumps(scale_curve, ensure_ascii=False)};\n\n")
        f.write(f"const MICRO_SUMMARY = {json.dumps(micro_summary, ensure_ascii=False)};\n\n")
        f.write(f"const SYNTHESIS_DATA = {json.dumps(synthesis, ensure_ascii=False)};\n")

    size_kb = os.path.getsize(out_path) / 1024
    print("[OK] Written: data/dashboard_data.js")
    print(f"    MICRO_DATA:      {len(micro_data)} rows")
    print(f"    SCALE_CURVE:     {len(scale_curve)} rows")
    print(f"    MICRO_SUMMARY:   {len(micro_summary)} groups")
    print(f"    SYNTHESIS_DATA:  {len(synthesis['response_curves'])} response_curves, "
          f"{len(synthesis['bridges'])} bridges")
    print(f"    File size:       {size_kb:.0f} KB")


if __name__ == "__main__":
    main()